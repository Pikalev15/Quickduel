import assert from "node:assert/strict";
import { createClient } from "@supabase/supabase-js";

const url=process.env.API_URL;
assert.ok(url && new URL(url).hostname === "127.0.0.1", "Only disposable local Supabase is allowed");
const options={auth:{persistSession:false,autoRefreshToken:false}};
const admin=createClient(url,process.env.SERVICE_ROLE_KEY??process.env.SECRET_KEY,options);
const player=createClient(url,process.env.ANON_KEY??process.env.PUBLISHABLE_KEY,options);
const status=await admin.rpc("get_workshop_release_status");
assert.ifError(status.error);
assert.deepEqual(status.data,{schemaVersion:1,prepared:true,activated:false});
assert.ok((await player.rpc("get_workshop_release_status")).error,"Anonymous readiness access must fail");
const auth=await player.auth.signInAnonymously();
assert.ifError(auth.error);
const queue={requested_playlist:"quick",requested_game:"memory_grid"};
const old=await player.rpc("join_matchmaking",queue);
assert.ifError(old.error);
assert.equal(old.data.queued,true);
assert.ifError((await player.rpc("leave_matchmaking")).error);
const ticket=await admin.rpc("issue_queue_duel_ticket",{requested_user_id:auth.data.user.id,requested_action:"join_matchmaking",requested_payload:queue});
assert.ifError(ticket.error);
const next=await player.rpc("server_queue_or_duel",{requested_ticket:ticket.data});
assert.ifError(next.error);
assert.equal(next.data.queued,true);
assert.ifError((await player.rpc("leave_matchmaking")).error);
const duration=await admin.rpc("game_answer_duration",{requested_game:"frequency_recall_v2"});
assert.ifError(duration.error);
assert.equal(duration.data,30000,"Legacy Frequency matches must retain 30-second scheduling until cutover");
console.log("Expansion verified: old and new matchmaking paths coexist.");
